#!/usr/bin/env node
// Concatenates src/*.mjs into a single dependency-free file for contexts
// that need one file to drop in (e.g. a Node.js core PR test fixture), plus
// a companion test bundle that runs src/*.test.mjs against it.
// Regenerate with `npm run bundle` whenever src/ changes.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const srcDir = path.join(rootDir, "src");
const outFile = path.join(rootDir, "dist", "kv.bundle.mjs");
const outTestFile = path.join(rootDir, "dist", "kv.bundle.test.mjs");

// Order matters: each file must appear after every file it imports from.
const FILES = [
	"constants.mjs",
	"errors.mjs",
	"utils.mjs",
	"keys.mjs",
	"statements.mjs",
	"kv.mjs",
];

// The supported public API — must match kv.d.ts exactly. Everything else any
// src/*.mjs file exports (encodeKey, prepareDb, TAG_STRING, the
// ERR_KVSTORE_* error classes, ...) is exported too, but only so
// dist/kv.bundle.test.mjs can reach it directly; none of it is part of the
// contract and it may change or disappear without notice. Notably, the
// ERR_KVSTORE_* error classes are deliberately NOT public — matching Node
// core convention (fs/http/net/crypto), errors are plain
// Error/TypeError/RangeError instances with a stable `.code`, not a bespoke
// exported class hierarchy. See kv.d.ts's `KVStoreErrorCode`.
const PUBLIC_EXPORTS = new Set(["openKv", "KVStore"]);

const IMPORT_RE = /^import\s[\s\S]*?from\s+["'][^"']+["'];\s*\n?/gm;
const IMPORT_CAPTURE_RE =
	/^import\s+([\s\S]*?)\s+from\s+["']([^"']+)["'];\s*\n?/gm;
const EXPORT_LIST_RE = /^export\s*\{([^}]+)\}\s*;\s*\n?/gm;
const EXPORT_DECL_CAPTURE_RE =
	/^export\s+(?:function|class|const|let|var)\s+(\w+)/gm;
const EXPORT_DECL_STRIP_RE =
	/^export\s+(?=(?:function|class|const|let|var)\s)/gm;

// ---- library bundle: dist/kv.bundle.mjs ------------------------------------
// Every module's exports are collected here, then split at the bottom into
// the curated public API (PUBLIC_EXPORTS, matching kv.d.ts) and everything
// else — internal helpers exported only so the generated test bundle below
// can reach them directly.

const externalImports = new Set();
const finalExports = new Set();
const bodies = [];

FILES.forEach((file) => {
	let src = readFileSync(path.join(srcDir, file), "utf8");

	// Hoist node: builtin imports; drop relative (./*.mjs) imports entirely
	// since everything they'd pull in is inlined into this same scope.
	src = src.replace(IMPORT_RE, (match) => {
		if (match.includes('"node:')) externalImports.add(match.trim());
		return "";
	});

	for (const m of src.matchAll(EXPORT_DECL_CAPTURE_RE)) finalExports.add(m[1]);
	src = src.replace(EXPORT_DECL_STRIP_RE, "");

	src = src.replace(EXPORT_LIST_RE, (_, names) => {
		for (const n of names
			.split(",")
			.map((s) => s.trim())
			.filter(Boolean)) {
			finalExports.add(n);
		}
		return "";
	});

	bodies.push(
		`// ---- ${file} ${"-".repeat(Math.max(0, 60 - file.length))}\n${src.trim()}`,
	);
});

const header = `// Auto-generated by scripts/bundle.mjs from src/*.mjs — do not edit directly.
// Regenerate with: npm run bundle
`;

const publicExports = [...finalExports]
	.filter((n) => PUBLIC_EXPORTS.has(n))
	.sort();
const internalExports = [...finalExports]
	.filter((n) => !PUBLIC_EXPORTS.has(n))
	.sort();
for (const name of PUBLIC_EXPORTS) {
	if (!finalExports.has(name)) {
		throw new Error(
			`PUBLIC_EXPORTS names "${name}", but no src/*.mjs file exports it`,
		);
	}
}

const output =
	`${header}\n${[...externalImports].sort().join("\n")}\n\n` +
	`${bodies.join("\n\n")}\n\n` +
	"// Public API — matches kv.d.ts exactly; this is the supported contract.\n" +
	`export { ${publicExports.join(", ")} };\n\n` +
	"// Internal implementation details, exported only so dist/kv.bundle.test.mjs\n" +
	"// can exercise them directly. NOT part of the public API: no stability\n" +
	"// guarantee, may change or disappear without notice.\n" +
	`export { ${internalExports.join(", ")} };\n`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, output);
console.log(
	`Wrote ${path.relative(rootDir, outFile)} (${output.length} bytes)`,
);

// ---- test bundle: dist/kv.bundle.test.mjs ----------------------------------
// Concatenates src/*.test.mjs, redirecting their relative imports (which
// normally point at individual src files) to the single bundle above.

const LOCAL_MODULES = new Set(FILES.map((f) => f.replace(/\.mjs$/, "")));
const TEST_FILES = readdirSync(srcDir)
	.filter((f) => f.endsWith(".test.mjs"))
	.sort();

const nodeImports = new Map(); // specifier -> { default: string|null, named: Set<string> }
const bundleNamed = new Set();
const testBodies = [];

function parseNamedClause(clause) {
	return clause
		.slice(1, -1)
		.split(",")
		.map((s) => s.trim())
		.filter(Boolean);
}

for (const file of TEST_FILES) {
	let src = readFileSync(path.join(srcDir, file), "utf8");

	src = src.replace(IMPORT_CAPTURE_RE, (_match, rawClause, specifier) => {
		const clause = rawClause.trim();
		const isNamed = clause.startsWith("{");

		if (specifier.startsWith("node:")) {
			if (!nodeImports.has(specifier)) {
				nodeImports.set(specifier, { default: null, named: new Set() });
			}
			const entry = nodeImports.get(specifier);
			if (isNamed) {
				for (const n of parseNamedClause(clause)) entry.named.add(n);
			} else {
				entry.default = clause;
			}
			return "";
		}

		// Relative import — must point at one of the bundled local modules.
		const moduleName = specifier.replace(/^\.\//, "").replace(/\.mjs$/, "");
		if (!LOCAL_MODULES.has(moduleName)) {
			throw new Error(`${file}: unexpected relative import "${specifier}"`);
		}
		if (!isNamed) {
			throw new Error(
				`${file}: default imports from local modules are not supported ("${specifier}")`,
			);
		}
		for (const n of parseNamedClause(clause)) bundleNamed.add(n);
		return "";
	});

	testBodies.push(src.trim());
}

const nodeImportLines = [...nodeImports.entries()]
	.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
	.map(([specifier, { default: def, named }]) => {
		const parts = [];
		if (def) parts.push(def);
		if (named.size > 0) parts.push(`{ ${[...named].sort().join(", ")} }`);
		return `import ${parts.join(", ")} from "${specifier}";`;
	});

const bundleImportLine = `import { ${[...bundleNamed].sort().join(", ")} } from "./kv.bundle.mjs";`;

const testHeader = `// Auto-generated by scripts/bundle.mjs from src/*.test.mjs — do not edit directly.
// Regenerate with: npm run bundle
// Runs the src/ test suite against dist/kv.bundle.mjs.
`;

const testOutput =
	`${testHeader}\n${nodeImportLines.join("\n")}\n${bundleImportLine}\n\n` +
	`${testBodies.join("\n\n")}\n`;

writeFileSync(outTestFile, testOutput);
console.log(
	`Wrote ${path.relative(rootDir, outTestFile)} (${testOutput.length} bytes)`,
);
